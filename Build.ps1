<#
.SYNOPSIS
  Inlines Modules\*.ps1 back into a single flattened .ps1 for ps2exe compilation.

.DESCRIPTION
  The main script dot-sources Modules\*.ps1 for development (so $script: scope works
  normally). ps2exe only compiles a single file, so this script replaces the
  "# --- BEGIN/END MODULE IMPORTS ---" block in the main script with the literal
  contents of each module, in order, and writes the result to .\dist\.
  Run this BEFORE your ps2exe command, then point ps2exe at the generated dist file
  instead of the multi-file source.

.PARAMETER SourceScript
  Path to the main .ps1 (the one with the dot-source markers). Defaults to the
  single .ps1 file found in this folder if only one exists.

.PARAMETER OutputPath
  Where to write the flattened script. Defaults to .\dist\<same filename>.
#>
param(
    [string]$SourceScript,
    [string]$OutputPath
)

$root = $PSScriptRoot

if (-not $SourceScript) {
    $candidates = Get-ChildItem -Path $root -Filter '*.ps1' -File |
    Where-Object { $_.Name -ne 'Build.ps1' }
    if ($candidates.Count -ne 1) {
        throw "Could not auto-detect the main script (found $($candidates.Count) candidates). Pass -SourceScript explicitly."
    }
    $SourceScript = $candidates[0].FullName
}

if (-not (Test-Path $SourceScript)) { throw "SourceScript not found: $SourceScript" }

if (-not $OutputPath) {
    $distDir = Join-Path $root 'dist'
    New-Item -ItemType Directory -Force -Path $distDir | Out-Null
    $OutputPath = Join-Path $distDir (Split-Path $SourceScript -Leaf)
}

$content = Get-Content -Path $SourceScript -Raw -Encoding UTF8

$beginMarker = '# --- BEGIN MODULE IMPORTS (Build.ps1 inlines these before ps2exe compilation) ---'
$endMarker = '# --- END MODULE IMPORTS ---'

$beginIdx = $content.IndexOf($beginMarker)
$endIdx = $content.IndexOf($endMarker)
if ($beginIdx -lt 0 -or $endIdx -lt 0 -or $endIdx -le $beginIdx) {
    throw "Could not find module-import markers in $SourceScript. Expected both:`n  $beginMarker`n  $endMarker"
}

# Find every dot-sourced module path referenced between the markers
$importBlock = $content.Substring($beginIdx, ($endIdx + $endMarker.Length) - $beginIdx)
$modulePattern = [regex]"\.\s*\(Join-Path \`$PSScriptRoot '([^']+)'\)"
$moduleMatches = $modulePattern.Matches($importBlock)
if ($moduleMatches.Count -eq 0) { throw "No dot-sourced module references found between the markers." }

$inlined = New-Object System.Text.StringBuilder
[void]$inlined.AppendLine('# --- INLINED MODULES (generated by Build.ps1 - do not edit by hand, edit Modules\*.ps1 instead) ---')
foreach ($m in $moduleMatches) {
    $relPath = $m.Groups[1].Value
    $modPath = Join-Path $root $relPath
    if (-not (Test-Path $modPath)) { throw "Module not found: $modPath" }
    [void]$inlined.AppendLine("# ---- inlined from $relPath ----")
    [void]$inlined.AppendLine((Get-Content -Path $modPath -Raw -Encoding UTF8))
}
[void]$inlined.AppendLine('# --- END INLINED MODULES ---')

$newContent = $content.Substring(0, $beginIdx) + $inlined.ToString() + $content.Substring($endIdx + $endMarker.Length)

# Verify the flattened result still parses before writing
$parseErrors = $null
[System.Management.Automation.Language.Parser]::ParseInput($newContent, [ref]$null, [ref]$parseErrors) | Out-Null
if ($parseErrors -and $parseErrors.Count -gt 0) {
    $parseErrors | ForEach-Object { Write-Host $_.ToString() -ForegroundColor Red }
    throw "Flattened script has $($parseErrors.Count) parse error(s) - not writing output."
}

Set-Content -Path $OutputPath -Value $newContent -Encoding UTF8
Write-Host "Build OK -> $OutputPath" -ForegroundColor Green
Write-Host "Run your ps2exe command against this file (not the multi-file source)." -ForegroundColor Cyan
